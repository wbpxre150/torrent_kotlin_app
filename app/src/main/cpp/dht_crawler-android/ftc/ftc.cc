/*
 * ftc: C ABI over the fastText inference path (Stage 4a).
 *
 * The wrapper is deliberately thin: one loaded model owns one
 * fasttext::FastText, and ftc_predict hands the feature line to the same
 * FastText::predictLine the `fasttext predict-prob` CLI calls, at threshold
 * 0.0. That keeps the numbers bit-identical to the reference CLI (predictLine
 * exponentiates the log probabilities, exactly like main.cc) and keeps the
 * predict path free of shared mutable state: FastText::predict allocates its
 * own Model::State per call, so concurrent ftc_predict calls on one model are
 * safe.
 */
#include "ftc.h"

#include <climits>
#include <cstdlib>
#include <new>
#include <sstream>
#include <string>
#include <utility>
#include <vector>

#include "fasttext.h"
#include "taxonomy.h"

namespace {

const char kLabelPrefix[] = "__label__";

/* fastText labels are `__label__<int>` for the adult student and
 * `__label__<taxonomy name>` for the category/tv_kind students. The ABI carries
 * ints, so a name is resolved through the generated taxonomy lookups (category
 * first, then tv_kind: the two name sets are disjoint) and -1 means "no usable
 * label". Those tables come from native/tparse/taxonomy.h, generated by
 * `cm gen-header` from config/taxonomy.json, so the label names are still
 * defined exactly once in the repo. */
int label_int(const std::string& label) {
    const size_t prefix = sizeof kLabelPrefix - 1;
    if (label.compare(0, prefix, kLabelPrefix) != 0) return -1;
    const char *suffix = label.c_str() + prefix;
    char *end = NULL;
    const long value = std::strtol(suffix, &end, 10);
    if (end != suffix && *end == '\0' && value >= INT_MIN && value <= INT_MAX) {
        return static_cast<int>(value);
    }
    const int category = tp_cat_from_name(suffix);
    if (category >= 0) return category;
    return tp_tv_from_name(suffix);
}

}  // namespace

struct ftc_model {
    fasttext::FastText fasttext;
};

extern "C" ftc_model_t *ftc_load(const char *path_ftz) {
    if (path_ftz == NULL) return NULL;
    ftc_model_t *model = new (std::nothrow) ftc_model_t();
    if (model == NULL) return NULL;
    try {
        model->fasttext.loadModel(std::string(path_ftz));
    } catch (...) {
        delete model;
        return NULL;
    }
    return model;
}

extern "C" int ftc_predict(
    ftc_model_t *model,
    const char *feature_text,
    int k,
    int *labels,
    float *probs) {
    if (model == NULL || feature_text == NULL || labels == NULL ||
        probs == NULL || k <= 0) {
        return 0;
    }

    /* FastText::predict takes an istream and predictLine reads exactly one
     * line from it, so a per-call istringstream is the whole "tokenizer".
     *
     * The trailing newline is load-bearing. `fasttext predict-prob` reads real
     * file lines, and Dictionary::readWord turns the line end into the EOS
     * ("</s>") token: EOS is dropped from the word list when out of
     * vocabulary, but its hash still enters addWordNgrams, so a stream without
     * the line end loses one ngram and shifts probabilities by ~1e-5 (this is
     * exactly what scripts/ftc_parity.sh caught). An already present trailing
     * '\n' just terminates the line one token earlier and changes nothing. */
    const std::string line = std::string(feature_text) + '\n';
    std::istringstream in(line);
    std::vector<std::pair<fasttext::real, std::string> > predictions;
    try {
        if (!model->fasttext.predictLine(in, predictions, k, 0.0f)) return 0;
    } catch (...) {
        return 0;  /* unsupervised model / corrupt state: no prediction */
    }

    size_t n = predictions.size();
    if (n > static_cast<size_t>(k)) n = static_cast<size_t>(k);
    for (size_t i = 0; i < n; i++) {
        labels[i] = label_int(predictions[i].second);
        probs[i] = static_cast<float>(predictions[i].first);
    }
    return static_cast<int>(n);
}

extern "C" void ftc_free(ftc_model_t *model) {
    delete model;
}
